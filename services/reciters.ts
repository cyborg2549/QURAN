export const getReciterById = (reciterId?: string): ReciterInfo => {
  if (!reciterId) {
    return QURAN_RECITERS[0];
  }
  return QURAN_RECITERS.find(r => r.id === reciterId) || QURAN_RECITERS[0];
};

export const getReciterAudioUrl = (
  reciterId: string | undefined,
  surahNumber: number,
  ayahNumber: number
): string => {
  const reciter = getReciterById(reciterId);
  const surahStr = surahNumber.toString().padStart(3, '0');
  const ayahStr = ayahNumber.toString().padStart(3, '0');
  return `https://everyayah.com/data/${reciter.folder}/${surahStr}${ayahStr}.mp3`;
};

export const getReciterFallbackAudioUrl = (
  reciterId: string | undefined,
  surahNumber: number,
  ayahNumber: number
): string => {
  const reciter = getReciterById(reciterId);
  const surahStr = surahNumber.toString().padStart(3, '0');
  const ayahStr = ayahNumber.toString().padStart(3, '0');
  return `https://everyayah.com/data/${reciter.fallbackFolder}/${surahStr}${ayahStr}.mp3`;
};
